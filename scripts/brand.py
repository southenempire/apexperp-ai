"""Generates the ApexPerp logo files from one set of glyph definitions."""
import os, sys
root = sys.argv[1]

# Block letters on a 10 x 14 grid; holes use evenodd.
G = {
 'A': 'M0 14V4L4 0H6L10 4V14H7V9H3V14ZM3 6H7V5L5.6 3H4.4L3 5Z',
 'P': 'M0 0H8L10 2V7L8 9H3V14H0ZM3 3V6H7V3Z',
 'E': 'M0 0H10V3H3V5.5H8V8.5H3V11H10V14H0Z',
 'X': 'M0 0H3.3L5 3.9L6.7 0H10L6.7 7L10 14H6.7L5 10.1L3.3 14H0L3.3 7Z',
 'R': 'M0 0H8L10 2V7L8.7 8.3L10 14H6.9L5.8 9H3V14H0ZM3 3V6H7V3Z',
}
WORD = 'APEXPERP'
ADV = 12  # letter width 10 + gap 2

def word_paths(x0, y0, s):
    out = []
    for i, ch in enumerate(WORD):
        tx = x0 + i * ADV * s
        out.append(f'<path transform="translate({tx:g} {y0:g}) scale({s:g})" d="{G[ch]}"/>')
    return ''.join(out)

# Mark on a 14 x 14 grid: a falling price line that stops just above a floor.
MARK_LINE = 'M3 3.3L6.1 6.4L8 4.5L11 7.5'
MARK_FLOOR = 'M3 9.4H11V11.2H3Z'
MARK_STROKE = 1.9

def mark(x, y, size, tile='#FFD400', ink='#0A0A09'):
    s = size / 14
    return (f'<rect x="{x:g}" y="{y:g}" width="{size:g}" height="{size:g}" fill="{tile}"/>'
            f'<g transform="translate({x:g} {y:g}) scale({s:g})"><path d="{MARK_LINE}" fill="none" stroke="{ink}" stroke-width="{MARK_STROKE}" stroke-linecap="butt" stroke-linejoin="miter"/><path d="{MARK_FLOOR}" fill="{ink}"/></g>')

def svg(w, h, body, title):
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w:g} {h:g}" width="{w:g}" height="{h:g}" role="img" aria-label="{title}">'
            f'<title>{title}</title>{body}</svg>\n')

out = os.path.join(root, 'public', 'brand')
os.makedirs(out, exist_ok=True)

def write(name, content):
    with open(os.path.join(out, name), 'w') as f:
        f.write(content)

write('mark.svg', svg(256, 256, mark(0, 0, 256), 'ApexPerp'))
# Lockups: mark + wordmark, for dark and light backgrounds.
H = 56; s = 4; gap = 18; ww = (len(WORD) * ADV - 2) * s
for name, ink in [('logo-dark.svg', '#F2EFE6'), ('logo-light.svg', '#0A0A09')]:
    write(name, svg(H + gap + ww, H, mark(0, 0, H) + f'<g fill="{ink}">{word_paths(H + gap, 0, s)}</g>', 'ApexPerp'))

# Social card 1200 x 630.
stripes = ''.join(f'<path d="M{x} 0h28l-28 28h-28z" fill="#FFD400"/>' for x in range(0, 1260, 56))
card = (
  '<rect width="1200" height="630" fill="#0A0A09"/>'
  f'<g>{stripes}</g>'
  f'{mark(80, 120, 120)}'
  f'<g fill="#F2EFE6">{word_paths(230, 135, 6.4)}</g>'
  '<text x="80" y="390" fill="#F2EFE6" font-family="HelveticaNeue-CondensedBold, Helvetica Neue, Arial Narrow, sans-serif" font-weight="700" font-size="96" letter-spacing="-1">GET TRIMMED,</text>'
  '<text x="80" y="490" fill="#FFD400" font-family="HelveticaNeue-CondensedBold, Helvetica Neue, Arial Narrow, sans-serif" font-weight="700" font-size="96" letter-spacing="-1">NOT LIQUIDATED.</text>'
  '<text x="80" y="566" fill="#969285" font-family="Menlo, monospace" font-size="26">Liquidation guard for dreamDEX perps on Somnia</text>'
  + ''.join(f'<rect x="{820 + i*11}" y="548" width="8" height="26" fill="{c}"/>' for i, c in enumerate(['#FF4533']*3 + ['#FFD400']*4 + ['#60DC78']*18))
)
write('og-image.svg', svg(1200, 630, card, 'ApexPerp: get trimmed, not liquidated'))

# React component data, so the app uses the exact same shapes.
ts = os.path.join(root, 'src', 'components', 'brandPaths.ts')
with open(ts, 'w') as f:
    f.write('// Generated by the brand script: shared shapes for the ApexPerp logo.\n')
    f.write(f"export const MARK_LINE = '{MARK_LINE}';\nexport const MARK_FLOOR = '{MARK_FLOOR}';\nexport const MARK_STROKE = {MARK_STROKE};\n")
    f.write(f"export const WORD_GLYPHS = {[G[c] for c in WORD]!r};\n".replace('"', "'"))
    f.write(f'export const LETTER_ADVANCE = {ADV};\n')
print('ok')
